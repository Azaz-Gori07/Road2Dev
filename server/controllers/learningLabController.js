      id: `defense-init-${Date.now()}`,
      role: 'assistant',
      text: `### 🎯 Project Defense Commenced!\nI have completed parsing your repository codebase and compiled the full **Architecture Understanding Report**.\n\nHere is your first Project Defense question based on your setup:\n\n**"${analysisReport.starterDefenseQuestion}"**`,
