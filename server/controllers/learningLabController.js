/**
 * POST create learning session
 */
export const createLearningSession = async (req, res) => {
  const { topic, mode = 'Intermediate', personality = 'The Coding Coach', sessionType = 'Concept Learning' } = req.body;
  if (!topic) {
    return res.status(400).json({ success: false, message: 'A topic is required.' });
  }

  try {
    const session = new LearningSession({
      userId: req.user._id,
      topic,
      mode,
      personality,
      sessionType,
      messages: []
    });

    // Auto-initialize first AI explanation to welcome user
    const aiResponse = await generateMentorResponse({
      topic,
      mode,
      messages: [{ role: 'user', text: `Hi, please teach me about ${topic}.` }],
      personality,
      sessionType
    });

    session.messages.push({
      id: `init-${Date.now()}`,
      role: 'assistant',
      text: aiResponse.text,
      playgroundChallenge: aiResponse.playgroundChallenge,
      structuredContent: aiResponse.structuredContent,
      timestamp: new Date()
    });

    // Save checklist tasks and suggestions generated by AI
    if (aiResponse.missionChecklistUpdates) {
      session.missionChecklist = aiResponse.missionChecklistUpdates.map(u => ({
        task: u.task,
        completed: !!u.completed
      }));
    } else {
      session.missionChecklist = [
        { task: `Understand basic concepts of ${topic}`, completed: true },
        { task: `Practice ${topic} in safe sandbox playground`, completed: false },
        { task: `Solve AI challenge to achieve mastery`, completed: false }
      ];
    }

    if (aiResponse.suggestedNextStep) {
      session.suggestedNextStep = aiResponse.suggestedNextStep;
    } else {
      session.suggestedNextStep = {
        title: `Explore ${topic} theory`,
        actionText: `Read through the AI mentor's initial explanation to understand structural definitions.`,
        targetTab: `notes`
      };
    }

    session.masteryPercentage = aiResponse.masteryDelta || 5;
    await session.save();

    return res.status(201).json({ success: true, data: session });
  } catch (error) {
    console.error('Create learning session failed:', error.message);
    return res.status(500).json({ success: false, message: 'Failed to start learning session.' });
  }
};

/**
 * POST send message in chat
 */
export const sendChatMessage = async (req, res) => {
  const { text } = req.body;
  if (!text) {
    return res.status(400).json({ success: false, message: 'Message text is required.' });
  }

  try {
    const session = await LearningSession.findOne({ _id: req.params.id, userId: req.user._id });
    if (!session) {
      return res.status(404).json({ success: false, message: 'Learning session not found.' });
    }

    // Append user message
    session.messages.push({
      id: `u-${Date.now()}`,
      role: 'user',
      text,
      timestamp: new Date()
    });

    // Generate AI response
    const aiResponse = await generateMentorResponse({
      topic: session.topic,
      mode: session.mode,
      messages: session.messages,
      personality: session.personality,
      sessionType: session.sessionType
    });

    session.messages.push({
      id: `a-${Date.now()}`,
      role: 'assistant',
      text: aiResponse.text,
      playgroundChallenge: aiResponse.playgroundChallenge,
      structuredContent: aiResponse.structuredContent,
      timestamp: new Date()
    });

    // Update suggested next actions & checklist objectives
    if (aiResponse.suggestedNextStep) {
      session.suggestedNextStep = aiResponse.suggestedNextStep;
    }
    
    if (aiResponse.missionChecklistUpdates) {
      aiResponse.missionChecklistUpdates.forEach(update => {
        const existing = session.missionChecklist.find(item => item.task.toLowerCase() === update.task.toLowerCase());
        if (existing) {
          existing.completed = !!update.completed;
        } else {
          session.missionChecklist.push({ task: update.task, completed: !!update.completed });
        }
      });
    }

    // Update mastery progress
    session.masteryPercentage = Math.min(100, session.masteryPercentage + (aiResponse.masteryDelta || 5));
    await session.save();

    return res.status(200).json({ success: true, data: session });
  } catch (error) {
    console.error('Send chat message failed:', error.message);
    return res.status(500).json({ success: false, message: 'Failed to process chat message.' });
  }
};

