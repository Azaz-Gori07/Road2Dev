// Ignore media, node_modules, build/dist, and lock files to prevent context overload
const IGNORE_PATTERNS = [
  /node_modules/i,
  /dist/i,
  /build/i,
  /coverage/i,
  /\.git/i,
  /\.cache/i,
  /package-lock\.json/i,
  /yarn\.lock/i,
  /pnpm-lock\.yaml/i,
  /\.(png|jpe?g|gif|svg|woff2?|eot|ttf|mp3|mp4|webm|zip|tar\.gz|ico|map)$/i
];

const isIgnored = (path) => {
  return IGNORE_PATTERNS.some(pattern => pattern.test(path));
};

// Fetch repository contents recursively from GitHub REST API with safe limit
const fetchGitHubRepoContents = async (owner, repo, path = '', filesCollected = [], depth = 0) => {
  if (depth > 4 || filesCollected.length > 35) return filesCollected; // Limit traversal to avoid rate limit or memory overflows
  
  try {
    const url = `https://api.github.com/repos/${owner}/${repo}/contents/${path}`;
    const headers = {};
    if (process.env.GITHUB_TOKEN) {
      headers.Authorization = `token ${process.env.GITHUB_TOKEN}`;
    }
    
    const response = await axios.get(url, { headers, timeout: 8000 });
    
    if (Array.isArray(response.data)) {
      for (const item of response.data) {
        if (isIgnored(item.path)) continue;
        
        if (item.type === 'dir') {
          await fetchGitHubRepoContents(owner, repo, item.path, filesCollected, depth + 1);
        } else if (item.type === 'file' && item.size < 120000) { // Limit size to 120KB
          filesCollected.push({
            path: item.path,
            downloadUrl: item.download_url,
            size: item.size
          });
        }
      }
    }
  } catch (error) {
    console.error(`GitHub fetch error for path ${path}:`, error.message);
  }
  return filesCollected;
};

